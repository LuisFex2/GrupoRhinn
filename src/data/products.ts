import { Product } from '../types/product';

export function parseDriveImages(rawUrl?: string): string[] {
  if (!rawUrl) return [];
  const segments = rawUrl.split(',').map(s => s.trim()).filter(Boolean);
  const results: string[] = [];
  for (const seg of segments) {
    const match = seg.match(/\/d\/([a-zA-Z0-9_-]+)/);
    if (match && match[1]) {
      results.push(`https://lh3.googleusercontent.com/d/${match[1]}=w800`);
    } else if (seg.startsWith('http')) {
      results.push(seg);
    }
  }
  return results;
}

export function getDriveThumbnailUrl(driveUrl?: string): string | null {
  if (!driveUrl) return null;
  const parsed = parseDriveImages(driveUrl);
  return parsed.length > 0 ? parsed[0] : null;
}

/**
 * Consolidates inventory items so that repeated rows of the same model
 * (which arise in inventory sheets due to different serial numbers/units)
 * are displayed exactly ONCE per model, accumulating their total stock.
 */
export function consolidateProducts(items: Product[]): Product[] {
  const map = new Map<string, Product>();

  for (const item of items) {
    const cleanModel = (item.modelo || '').trim().toUpperCase();
    const cleanBrand = (item.marca || '').trim().toUpperCase();
    const cleanCat = (item.categoria || '').trim().toUpperCase();
    const cleanCond = (item.condicion || '').trim().toUpperCase();
    const cleanName = (item.nombre || '').trim().toUpperCase();

    // If model is a generic dimension/label (e.g. "14-43 PLG" for brackets),
    // include name to avoid merging different product types.
    // For standard appliances/TVs, brand + model + condition groups all identical models.
    const isGenericModel = !cleanModel || cleanModel.length <= 3 || cleanModel.includes('PLG') || cleanModel === 'GENÉRICO' || cleanModel === 'GENERICO';

    const groupKey = isGenericModel
      ? `${cleanCat}__${cleanBrand}__${cleanName}__${cleanModel}__${cleanCond}`
      : `${cleanCat}__${cleanBrand}__${cleanModel}__${cleanCond}`;

    if (!map.has(groupKey)) {
      map.set(groupKey, {
        ...item,
        stock: item.stock || 1,
      });
    } else {
      const existing = map.get(groupKey)!;
      existing.stock += (item.stock || 1);
      // Keep best thumbnail / driveUrl
      if (!existing.thumbnailUrl && item.thumbnailUrl) {
        existing.thumbnailUrl = item.thumbnailUrl;
        existing.driveUrl = item.driveUrl;
      }
      if ((!existing.images || existing.images.length === 0) && item.images && item.images.length > 0) {
        existing.images = item.images;
      }
      if (item.destacado) {
        existing.destacado = true;
      }
    }
  }

  return Array.from(map.values());
}

